function svg(rects, bg) {
  const body = rects
    .map(
      (r) =>
        `<rect x="${r[0]}" y="${r[1]}" width="${r[2]}" height="${r[3]}" fill="${r[4]}"/>`,
    )
    .join("");
  const bgRect = bg ? `<rect width="64" height="64" fill="${bg}"/>` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" shape-rendering="crispEdges">${bgRect}${body}</svg>`;
}

function tile(shades) {
  const rects = [];
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      const i = (x + y) % shades.length;
      rects.push([x * 8, y * 8, 8, 8, shades[i]]);
    }
  }
  return rects;
}

