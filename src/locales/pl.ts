export function profileCountLabel(n: number): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  let word: string = pl.profile.many;
  if (n === 1) word = pl.profile.one;
  else if (last >= 2 && last <= 4 && (abs < 12 || abs > 14)) word = pl.profile.few;
  return `${n} ${word}`;
}
